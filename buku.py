class Buku:
    def __init__(self, kode_buku, judul_buku, penulis, tahun_terbit):
        self.kode_buku = kode_buku
        self.judul_buku = judul_buku
        self.penulis = penulis
        self.tahun_terbit = tahun_terbit

def tampilkan_info(self):
    print("Kode Buku :", self.kode_buku)
    print("Judul Buku :", self.judul)
    print("Penulis :", self.penulis)
    print("Tahun Terbit :", self.tahun_terbit)

def ubah_data(self, judul_buku, penulis, tahun_terbit):
        self.judul_buku = judul_buku
        self. penulis = penulis
        self.tahun_terbit = tahun_terbit

def format_simpan(self):
     return f"{self.kode_buku}{self.judul}{self.penulis}{self.tahun_terbit}"
    